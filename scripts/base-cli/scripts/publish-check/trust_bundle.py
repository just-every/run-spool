"""Public CA metadata inside pinned WebPKI trust-bundle artifacts.

A committed trust-bundle.json, regenerated by the build that produces its
artifacts, pins each artifact's SHA-256 and lists the SHA-256 of every compiled
trust anchor's subject Name and SubjectPublicKeyInfo DER. Its webpki-roots
release must be the one the same directory's Cargo.lock locks. Only attribute
values of a subject Name parsed from such an artifact, whose anchor's subject
and public key both occur there as a listed pair, are certificate metadata.
"""
from collections import namedtuple
from functools import lru_cache
import hashlib
import json
import re
from der import names, public_keys

MANIFEST = 'trust-bundle.json'
REGISTRY = 'registry+https://github.com/rust-lang/crates.io-index'
DIGEST = re.compile(r'[0-9a-f]{64}')
ARTIFACT = re.compile(r'[A-Za-z0-9_][A-Za-z0-9_.-]*')
Bundle = namedtuple('Bundle', 'digest anchors')


def locked_packages(lock):
    packages, current = [], None
    for line in lock.decode('utf-8').splitlines():
        if line == '[[package]]':
            current = {}
            packages.append(current)
        elif line.startswith('['):
            current = None
        elif current is not None and ' = "' in line and line.endswith('"'):
            key, value = line.split(' = "', 1)
            current[key] = value[:-1]
    return packages


@lru_cache(maxsize=16)
def parse(manifest, lock):
    try:
        record = json.loads(manifest)
        roots, artifacts, anchors = record['roots'], record['artifacts'], record['anchors']
        if (set(record) != {'schemaVersion', 'roots', 'artifacts', 'anchors'} or record['schemaVersion'] != 1 or
                set(roots) != {'crate', 'version', 'checksum'} or roots['crate'] != 'webpki-roots' or
                not isinstance(roots['version'], str) or not DIGEST.fullmatch(roots['checksum']) or
                not artifacts or not all(isinstance(name, str) and ARTIFACT.fullmatch(name) and isinstance(digest, str) and DIGEST.fullmatch(digest)
                                         for name, digest in artifacts.items()) or
                not anchors or not all(isinstance(a, dict) and set(a) == {'subject', 'spki'} and
                                       all(isinstance(v, str) and DIGEST.fullmatch(v) for v in a.values()) for a in anchors)):
            return None
        locked = [p for p in locked_packages(lock) if p.get('name') == roots['crate']]
    except (ValueError, TypeError, KeyError, AttributeError, UnicodeError):
        return None
    if len(locked) != 1 or locked[0] != dict(name=roots['crate'], version=roots['version'], source=REGISTRY, checksum=roots['checksum']):
        return None
    pairs = frozenset((a['subject'], a['spki']) for a in anchors)
    return tuple((name, Bundle(digest, pairs)) for name, digest in artifacts.items())


def bundles(paths, read):
    """{artifact path: Bundle} declared by valid manifests among a tree's paths."""
    result = {}
    for path in paths:
        directory, _, name = path.rpartition('/')
        prefix = directory + '/' if directory else ''
        if name != MANIFEST or prefix + 'Cargo.lock' not in paths:
            continue
        for artifact, bundle in parse(read(path), read(prefix + 'Cargo.lock')) or ():
            result[prefix + artifact] = bundle
    return result


def anchor_values(data, bundle):
    """Attribute value spans of verified trust-anchor subjects in exact pinned bytes."""
    if hashlib.sha256(data).hexdigest() != bundle.digest:
        return []
    subjects = {subject for subject, _ in bundle.anchors}
    keys = {spki for _, spki in bundle.anchors}
    found = {}
    for start, end, values in names(data):
        digest = hashlib.sha256(data[start:end]).hexdigest()
        if digest in subjects:
            found.setdefault(digest, []).append(values)
    present = {digest for start, end in public_keys(data)
               if (digest := hashlib.sha256(data[start:end]).hexdigest()) in keys}
    return [span for subject, spki in bundle.anchors if spki in present
            for values in found.get(subject, ()) for span in values]
