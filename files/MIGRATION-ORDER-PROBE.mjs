import assert from 'node:assert/strict';
import {readFile,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {createRequire} from 'node:module';
const root='/workspace/run-spool';
const require=createRequire(root+'/package.json');
const {Miniflare,convertV4MiniflareOptions,Log,LogLevel}=require(require.resolve('miniflare',{paths:[require.resolve('wrangler/package.json')]}));
const {unstable_splitSqlQuery}=require('wrangler');
const sentryHead='8d44b36e050201ea0923e4d767ba346f9466328e';
const sentryName='0110_sentry_roster_proposals.sql';
const sentry=execFileSync('git',['show',`${sentryHead}:migrations/core/${sentryName}`],{cwd:root,encoding:'utf8'});
const baseFiles=(await readdir(root+'/migrations/core')).filter(f=>f.endsWith('.sql')&&f<'0110').sort();
const keyName='0111_key_names_and_use.sql';
const key=await readFile(root+'/migrations/core/'+keyName,'utf8');
const runtime=new Miniflare(convertV4MiniflareOptions({modules:true,script:'export default {}',log:new Log(LogLevel.ERROR),d1Databases:{DB:'migration-order'}}));
try {
 const db=await runtime.getD1Database('DB');
 const apply=async sql=>db.batch(unstable_splitSqlQuery(sql).filter(q=>!/^PRAGMA foreign_keys\s*=\s*ON;?$/i.test(q.trim())).map(q=>db.prepare(q)));
 for(const file of baseFiles)await apply(await readFile(root+'/migrations/core/'+file,'utf8'));
 await db.prepare('CREATE TABLE rer_migrations(name TEXT PRIMARY KEY,sha256 TEXT NOT NULL)').run();
 for(const file of baseFiles)await db.prepare('INSERT INTO rer_migrations VALUES(?,?)').bind(file,createHash('sha256').update(await readFile(root+'/migrations/core/'+file)).digest('hex')).run();
 await db.prepare("INSERT INTO projects VALUES('upgrade-proof','Synthetic upgrade project',1)").run();
 for(const [i,kind] of ['ingest','agent','deploy'].entries())await db.prepare('INSERT INTO credentials(hash,project,kind,created,revoked) VALUES(?,?,?,?,?)').bind(String(i+1).repeat(64),'upgrade-proof',kind,i+1,kind==='agent'?9:null).run();
 const rows=async sql=>(await db.prepare(sql).all()).results;
 const before=await rows('SELECT * FROM credentials ORDER BY hash');
 const baseLedger=await rows('SELECT * FROM rer_migrations ORDER BY name');
 await apply(sentry);
 await db.prepare('INSERT INTO rer_migrations VALUES(?,?)').bind(sentryName,createHash('sha256').update(sentry).digest('hex')).run();
 const roster={id:'proposal-proof',project:'upgrade-proof',kind:'member',payload:'{"role":"member"}',state:'pending',version:1,created:4};
 await db.prepare('INSERT INTO spool_import_proposals(id,project,kind,payload,state,version,created) VALUES(?,?,?,?,?,?,?)').bind(...Object.values(roster)).run();
 const rosterBefore=await rows('SELECT * FROM spool_import_proposals');
 await apply(key);
 await db.prepare('INSERT INTO rer_migrations VALUES(?,?)').bind(keyName,createHash('sha256').update(key).digest('hex')).run();
 const after=await rows('SELECT * FROM credentials ORDER BY hash');
 assert.deepEqual(after.map(({name,last_used,...r})=>r),before);
 assert.ok(after.every(r=>r.name===''&&r.last_used===null));
 assert.deepEqual(await rows('SELECT * FROM spool_import_proposals'),rosterBefore);
 assert.deepEqual((await rows('SELECT * FROM rer_migrations ORDER BY name')).slice(0,-2),baseLedger);
 assert.deepEqual((await rows('SELECT name FROM rer_migrations ORDER BY name')).slice(-2).map(r=>r.name),[sentryName,keyName]);
 console.log(JSON.stringify({status:'passed',baseMigrations:baseFiles.length,baseLast:baseFiles.at(-1),order:[sentryName,keyName],sentryHead,sentrySha256:createHash('sha256').update(sentry).digest('hex'),keysSha256:createHash('sha256').update(key).digest('hex'),credentialRowsBefore:before.length,credentialRowsAfter:after.length,rosterRowsBefore:rosterBefore.length,rosterRowsAfter:(await rows('SELECT * FROM spool_import_proposals')).length,ledgerRowsBefore:baseLedger.length,ledgerRowsAfter:(await rows('SELECT * FROM rer_migrations')).length,authorityPreserved:true,metadataDefaults:true,rosterPreserved:true},null,2));
}finally{await runtime.dispose()}
