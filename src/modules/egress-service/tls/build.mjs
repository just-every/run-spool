import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { manifest, roots } from './trust-bundle.mjs';
const here = fileURLToPath(new URL('./', import.meta.url));
const test = process.argv.includes('--test'), check = process.argv.includes('--check');
if (process.argv.slice(2).some(flag => !['--test','--check'].includes(flag))) throw new Error('use --test and/or --check');
const target = check ? 'target/reproduce' : 'target';
if (execFileSync('wasm-bindgen', ['--version'], {encoding:'utf8'}).trim() !== 'wasm-bindgen 0.2.114') throw new Error('wasm-bindgen 0.2.114 required');
execFileSync('rustup', ['run', '1.90.0', 'cargo', 'build', '--locked', '--target-dir', target, '--target', 'wasm32-unknown-unknown', '--release', ...(test ? ['--features', 'test-roots'] : [])], {
  cwd: here, stdio: 'inherit', env: { ...process.env, CARGO_BUILD_JOBS: '2', RUSTFLAGS: '-C link-arg=--max-memory=16777216', CC_wasm32_unknown_unknown: 'clang', AR_wasm32_unknown_unknown: 'llvm-ar', RUSTC: execFileSync('rustup', ['which', '--toolchain', '1.90.0', 'rustc'], { encoding: 'utf8' }).trim() },
});
execFileSync('wasm-bindgen', ['--target', 'web', '--out-dir', `${target}/bindgen`, '--out-name', 'engine', `${target}/wasm32-unknown-unknown/release/rer_egress_tls.wasm`], { cwd: here, stdio: 'inherit' });
const bytes = await readFile(new URL(`${target}/bindgen/engine_bg.wasm`, import.meta.url));
const module = new WebAssembly.Module(bytes), imports = WebAssembly.Module.imports(module);
if (imports.some(e => e.module !== './engine_bg.js')) throw new Error('unexpected WASM imports');
if (!test && WebAssembly.Module.exports(module).some(e => e.name === 'test_root')) throw new Error('test roots in production build');
if (test && JSON.stringify(imports) !== JSON.stringify(WebAssembly.Module.imports(new WebAssembly.Module(await readFile(new URL('./egress.wasm', import.meta.url)))))) throw new Error('test module requires different glue');
// Keep generated cryptographic imports intact, remove unused asynchronous asset loaders,
// and isolate the generated heap/memory references in one closure per TLS connection.
const glue = (await readFile(new URL(`${target}/bindgen/engine.js`, import.meta.url), 'utf8'))
  .replace(/async function __wbg_load[\s\S]*?(?=function initSync)/, '')
  .replace(/async function __wbg_init[\s\S]*?(?=export \{ initSync[, ])/, '')
  .replace(/^export \{[^}]+\};?$/gm, '').replace(/^export default .*$/gm, '').replace(/^export /gm, '');
if (glue.includes('fetch(') || glue.includes('async function')) throw new Error('unexpected asynchronous WASM loader');
const wrapped = '// Generated by tls/build.mjs with wasm-bindgen 0.2.114. Do not edit.\nexport function instantiate(module) {\n' + glue + '\nreturn initSync({ module });\n}\n';
const file = test ? 'test.wasm' : 'egress.wasm', output = new URL(file, import.meta.url);
const bundleFile = new URL('./trust-bundle.json', import.meta.url), recorded = await readFile(bundleFile, 'utf8').catch(() => null);
const bundle = manifest(recorded && JSON.parse(recorded), file, bytes, roots(here, ['rustup', 'run', '1.90.0', 'cargo']));
if (check) {
  if (!bytes.equals(await readFile(output)) || !test && wrapped !== await readFile(new URL('./engine.js', import.meta.url), 'utf8')) throw new Error('TLS build is not byte-for-byte reproducible');
  if (bundle !== recorded) throw new Error('trust-bundle.json does not match this build');
} else {
  await writeFile(output, bytes);
  if (!test) await writeFile(new URL('./engine.js', import.meta.url), wrapped);
  await writeFile(bundleFile, bundle);
}
console.log(JSON.stringify({file, bytes:bytes.length, ...(check ? {reproduced:true} : {}), imports}));
